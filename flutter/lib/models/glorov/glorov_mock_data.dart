  static GlorovProduct? getProductById(String id) {
    try {
      return products.firstWhere((p) => p.id == id);
    } catch (_) {
      return null;
    }
  }

  static GlorovProduct? getProductBySlug(String slug) {
    try {
      return products.firstWhere((p) => p.slug == slug);
    } catch (_) {
      return null;
    }
  }

  static List<GlorovProduct> getProductsByCategory(String categoryTitle) {
    if (categoryTitle.toLowerCase() == 'all' ||
        categoryTitle.toLowerCase() == 'all botanical') {
      return products;
    }
    return products
        .where((p) => p.category.toLowerCase() == categoryTitle.toLowerCase())
        .toList();
  }

  static List<GlorovProduct> getRelatedProducts(GlorovProduct product) {
    if (product.relatedProductIds.isEmpty) {
      return products.where((p) => p.id != product.id).take(3).toList();
    }
    return products
        .where((p) => product.relatedProductIds.contains(p.id))
        .toList();
  }

  static List<GlorovProduct> searchProducts(String query) {
    final clean = query.trim().toLowerCase();
    if (clean.isEmpty) return products;
    return products.where((p) {
      final inTitle = p.title.toLowerCase().contains(clean);
      final inBotanical = p.botanicalName.toLowerCase().contains(clean);
      final inCategory = p.category.toLowerCase().contains(clean);
      final inSubcategory = p.subcategory.toLowerCase().contains(clean);
      final inDesc = p.shortDescription.toLowerCase().contains(clean);
      final inBadges = p.badges.any((b) => b.toLowerCase().contains(clean));
      return inTitle ||
          inBotanical ||
          inCategory ||
          inSubcategory ||
          inDesc ||
          inBadges;
    }).toList();
  }
